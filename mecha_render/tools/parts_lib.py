# ---------------------------------------------------------------- 机械感零件族
# ★ 用户：「部件这个就和 freedom 级别的差太多了吧，机体按板甲来走的话，
#   部件总得复杂一点吧」—— 对。板甲是**机体**的选择，武器没有理由跟着光滑：
#   武器的复杂度预算是整个项目里最高的（离镜头最近、被拿在手里、单件陈列）。
#
#   机械感不靠「多加面」，靠五件具体的事（全部 ≥ READ_MIN）：
#     ① 分件线（seam）：一个大面切成几块板，缝里露暗色
#     ② 紧固件（bolts）：26 mm 六角头，凑近是零件，拉远是一条质感线
#     ③ 功能件（louver / rail / port / tooth）：散热百叶、导轨、炮口、齿轨
#     ④ 内构外露（spar）：罩板之间露出一段骨架，说明壳是**装上去**的
#     ⑤ 箍（belt）：绕体一圈的分段环，把长壳体读成「三段接起来的」
def blk(n, x0, x1, y0, y1, z0, z1, mat=FRAME):
    """直角方块（c=0 → 硬边，不做倒角）：紧固件、导轨、指示灯都用它。"""
    n.children.append(L([(y0, R(x0, x1, z0, z1, 0.0)),
                         (y1, R(x0, x1, z0, z1, 0.0))], mat))


def seam(n, y, x0, x1, z0, z1, mat=INK, th=0.011):
    """横向分件缝：一条贴在面上的暗色薄片（22 mm 宽，≥4 px）。"""
    n.children.append(L([(y - th, R(x0, x1, z0, z1, 0.0)),
                         (y + th, R(x0, x1, z0, z1, 0.0))], mat))


def bolts(n, ys, x, z, s=0.013, mat=INK, axis='x'):
    """一排紧固件（26 mm 六角头）。axis='x' 表示沿 X 面（法线朝 X）排。"""
    for y in ys:
        if axis == 'x':
            blk(n, x - 0.005, x + 0.008, y - s, y + s, z - s, z + s, mat)
        else:
            blk(n, x - s, x + s, y - s, y + s, z - 0.005, z + 0.010, mat)


def louver(n, y0, y1, x0, x1, z, k=4, mat=INK, th=0.011):
    """百叶散热口：k 条横向薄片。这是「机械感」性价比最高的一种零件。"""
    step = (y1 - y0) / k
    for i in range(k):
        y = y0 + step * (i + 0.5)
        blk(n, x0, x1, y - th, y + th, z - 0.006, z + 0.014, mat)


def rail(n, y0, y1, x, z, w=0.021, mat=FRAME):
    """导轨 / 加强条：一条细长凸起。"""
    blk(n, x - w, x + w, y0, y1, z - 0.008, z + 0.018, mat)


def belt(n, y, hw, hd, h=0.070, out=0.030, mat=ARMOR2, c=None):
    """箍：绕体一圈的分段环。四截面出倒角，读作「壳体是三段接起来的」。

    这是本版最重要的新零件：长壳体（步枪机匣 1.2 m、浮游炮 1.7 m）
    第一版是一整块光滑放样，加多少螺栓都救不回来 —— 因为**没有横向分段**。
    """
    cc = (min(hw, hd) * 0.25) if c is None else c
    n.children.append(L([
        (y - h * 0.5, R(-hw + out, hw - out, -hd + out, hd - out, cc)),
        (y - h * 0.5 + 0.016, R(-hw, hw, -hd, hd, cc)),
        (y + h * 0.5 - 0.016, R(-hw, hw, -hd, hd, cc)),
        (y + h * 0.5, R(-hw + out, hw - out, -hd + out, hd - out, cc)),
    ], mat))


def spar(n, y0, y1, x, z0, z1, mat=FRAME, w=0.026):
    """外露骨架条：从罩板缝里露出来的一段深色结构（沿 X 面）。"""
    blk(n, x - w, x + w, y0, y1, z0, z1, mat)


def spar_z(n, y0, y1, x0, x1, z, mat=FRAME, d=0.030):
    """外露骨架条（沿 Z 面，顶/底）。"""
    blk(n, x0, x1, y0, y1, z - 0.010, z + d, mat)


def port(n, y, x, z, r, d=0.070, mat=ARMOR2, bore=INK):
    """炮口：外圈凸缘 + 内圈暗膛 + 三点卡爪。r 是外半径。"""
    n.children.append(L([
        (y, R(x - r, x + r, z - r, z + r, r * 0.35)),
        (y + d * 0.45, R(x - r, x + r, z - r, z + r, r * 0.35)),
        (y + d, R(x - r * 0.80, x + r * 0.80, z - r * 0.80, z + r * 0.80,
                  r * 0.28)),
    ], mat))
    n.children.append(L([
        (y + d * 0.5, R(x - r * 0.58, x + r * 0.58, z - r * 0.58, z + r * 0.58,
                        r * 0.20)),
        (y + d * 1.02, R(x - r * 0.58, x + r * 0.58, z - r * 0.58, z + r * 0.58,
                         r * 0.20)),
    ], bore))


def tooth(n, y0, y1, x0, x1, z, h=0.030, mat=FRAME, k=6):
    """齿轨：一排 h 高的齿（后坐齿 / 瞄具轨 / 防滑齿）。"""
    step = (y1 - y0) / k
    for i in range(k):
        y = y0 + step * (i + 0.5)
        blk(n, x0, x1, y - step * 0.28, y + step * 0.28, z, z + h, mat)


def box_beam(y0, y1, hw, hd, wall=0.02, mat=FRAME, taper=1.0, name='beam'):
    """方箱梁：翼盒、挂架、步枪机匣都用它。

    ★ 上一版翼片是**一整块 0.075 的板**，没有梁。按薄板受压屈曲算，
      0.92 m 宽的蒙皮在 0.43 MPa 就屈曲，而工作应力 5–37 MPa —— 差 12–86 倍。
      所以「翼撑不住」这句话在力学上是对的，只是原因不在强度，在**没有梁**。
    """
    n = Node(name)
    hw1, hd1 = hw * taper, hd * taper
    n.children.append(L([
        (y0, R(-hw, hw, -hd, hd, min(hw, hd) * 0.25)),
        (y1, R(-hw1, hw1, -hd1, hd1, min(hw1, hd1) * 0.25)),
    ], mat))
    for sx in (+1, -1):
        for sz in (+1, -1):
            n.children.append(L([
                (y0, R(sx * hw - 0.022, sx * hw + 0.022,
                       sz * hd - 0.022, sz * hd + 0.022, 0.008)),
                (y1, R(sx * hw1 - 0.022, sx * hw1 + 0.022,
                       sz * hd1 - 0.022, sz * hd1 + 0.022, 0.008)),
            ], ARMOR2))
    return n


def mount(name, child, pos=(0, 0, 0), rot=(0, 0, 0)):
    """把件转到挂载姿态。Node.rot 单位是**度**（r3d 内部自己转弧度）。"""
    w = Node(name, pos=pos, rot=rot)
    w.children.append(child)
    return w


