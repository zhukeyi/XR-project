def PLT(x0, x1, zo, th, b=0.05, rev=False):
    """平面内折一道的薄甲片截面（5 点，凸）。

    zo = 两端外表面的 z；中部前凸 b；内表面是**直的** → 端部厚、脊线处薄 (th−b)。
    ★ 不能做成「等厚弯板」：等厚弯板在 (x,z) 里是非凸多边形，而 `loft_poly` 的端盖
      是**扇形三角化**，非凸截面会翻面。做成「外凸内直」后整块是凸的，端盖安全。
    ★ `b ≤ 0.45·th`，否则脊线处厚度趋零，渲染上会出针孔。
    ★ 点的**绕向必须是逆时针**（x 右、z 上）。`loft_poly` 按绕向定外法线：
      顺时针截面会让甲片的朝外面变成朝里 → 光栅化时被背面剔除 → 从正面直接
      看穿到后面的暗色基体。这个 bug 的表现是「整块大腿正面发黑」，
      很容易被误读成「材质配错了」或「缝太宽」，其实是绕向反了（踩过一次）。
    ★ `rev=True` 用于**后甲**（外表面在 −z 侧）：只把输出的 z 取负会让绕向
      反过来，所以还必须**倒序**。做法是「先构造逆时针的 +z 甲片，再镜像」，
      因此 zo 依旧填「平坦面到中线的距离（正数）」，
      例如外表面 −0.44 / 内表面 −0.28 的后甲写 `PLT(x0,x1, 0.39, 0.11, 0.05, rev=True)`。
      ★ 不要把 zo 也取负 —— 那是双重镜像，甲片会跑到 +z 侧（踩过一次）。
    """
    if x0 > x1:
        x0, x1 = x1, x0
    xm = 0.5 * (x0 + x1)
    pts = [(x0, zo - th), (x1, zo - th), (x1, zo), (xm, zo + b), (x0, zo)]
    if rev:
        return [(x, -z) for (x, z) in pts[::-1]]
    return pts


