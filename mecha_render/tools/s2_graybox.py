def xform(name, child, dy=0.0, sy=1.0, sxz=1.0, pivot=0.0, px=0.0, pz=0.0, ox=0.0):
    """比例变换：把 child 整体按「pivot 固定点 + 三轴缩放」重映射。

    要的映射：
        x' = ox + px + sxz·(x − px)
        y' = dy + pivot + sy·(y − pivot)
        z' = pz + sxz·(z − pz)

    ★ `px/pz` 是**缩放不动点**，`ox` 才是**纯平移**。两者不能混：
      当 sxz = 1.0 时 x' = ox + x，而 px 完全不起作用。
      这一轮把腿往外挪 0.22 m 时踩过：只给了 px，包络和站位一字未变，
      图上「腿还是并着」，查了半天以为 LEG_XW 没生效。
    用嵌套节点实现（Node.local = T·Rx·Ry·Rz·S，外层先缩放后平移，
    内层只做反向平移）：
        外层 pos = (px, dy+pivot, pz) + scl=(sxz, sy, sxz)
        内层 pos = (−px, −pivot, −pz)
    验证（腿 sxz=1.0 / px=0.78）：x' = 0.78 + 1.0·(x − 0.78) = x ✓

    ★ 踩过的坑（必须记住）：外层 pos 的 x 槽不能写 0 —— 当 sxz=1.0 时
      0 + 1.0·(x − px) 等于把整条腿**平移到中线**，两条腿重合成一条、
      手臂缩进躯干。图上表现为「只有一条腿的机体」，看包络完全看不出来
      （包络仍然 4.48 × 7.90，因为畸变是对称的）。
    """
    w = Node(name, pos=(px + ox, dy + pivot, pz), scl=(sxz, sy, sxz))
    c = Node('', pos=(-px, -pivot, -pz))
    c.children.append(child)
    w.children.append(c)
    return w


def squeeze3(name, child, anchor, k):
    """三轴**各自**缩放，固定点 anchor=(ax, ay, az)。

    为什么不用现成的 xform
      xform 只有一个 `sxz`，x 与 z 绑死。肩甲要的是「x 压 25%，z 也压 25%，
      y 压 25%」—— 这一版刚好三轴同比例，理论上 sxz 就够；但肩甲的纵深
      （1.13 m）和宽度（2.24→）来源不同：宽度是被折叠翼根撑出来的，
      纵深是它自己的造型。下一次若要单独动 x，sxz 就写不出来，
      与其那时再改签名，不如现在就给一个三轴独立的入口。

        x' = ax + kx·(x − ax)
        y' = ay + ky·(y − ay)
        z' = az + kz·(z − az)

    实现沿用 xform 的两层套路（外层 T·S、内层只做反向平移）：
        p_child = p − anchor   →   p' = anchor + k·(p − anchor)
    """
    ax, ay, az = anchor
    kx, ky, kz = k
    w = Node(name, pos=(ax, ay, az), scl=(kx, ky, kz))
    c = Node('', pos=(-ax, -ay, -az))
    c.children.append(child)
    w.children.append(c)
    return w


# ★ 三条警告（比例层能做的和不能做的）
#   ① 它只改**相位**，不改几何：非均匀缩放会让倒角角度变一点（7% 量级可接受），
#      但**做不出「踝收、腓肠肌、膝收」这种沿长度变化的轮廓** —— 那必须改坐标。
#   ② 背包**只平移不压缩**：容积账（§23.2：7.589 毛 / 5.313 可用）是按几何算的，
#      压 y 6% 会把可用量压到 5.0，门就擦边了。所以 bay / funnels 的 sy 恒为 1。
#   ③ 头和背包**不参与躯干压缩**：头压了会变成「扁头」，背包压了容积口径就变。


# ---------------------------------------------------------------- 组装
def build():
    root = Node('s2')
    P = PROP
    pv = P['pivot']
    # ★ 头高：参考 1.639 H，我们 1.400 H（唯一还差 0.24 H 的一条）。
    #   反解（不动点 p = 头顶 7.930，头顶不动、下巴往下长）：
    #       sy = 1.300/1.110 = 1.171        （1.639 H × 0.793 = 1.300 m，我们现 1.110 m）
    #       b  = 6.630 − 1.171×6.820 = −1.356
    #       dy = b − p(1−sy) = −1.356 − 7.930×(−0.171) = 0.000
    #   所以只需要 sy，不需要 dy —— 这也是"头顶不动点"这个选法的好处：
    #   头一长，动的只有下巴（6.820 → 6.630），肩甲顶/胸顶那几条线一根都不受影响。
    #   ★ 坑：不动点必须取**局部**头顶 7.950，不是世界 7.930。头节点原本带 dy=−0.020，
    #     所以局部最高点是 7.950。第一版把 p 写成 7.930，于是 7.950 被放大到
    #     7.930 + 1.171×0.020 = 7.953 —— 总高从 7.930 涨到 7.953，"头顶"那根线
    #     归一之后还是 10.000（看不出来），只有绝对包络涨了。改 p=7.950 + dy=−0.020。
    root.children.append(xform('head', build_head(), dy=-0.020, sy=1.171, pivot=7.950))
    # 躯干：压短 + 变窄，固定点 = 腰底
    root.children.append(xform('chest', build_chest(), dy=P['dy_up'],
                               sy=P['tor_sy'], sxz=P['tor_sxz'], pivot=pv))
    # 腰：★ 单独一套（比胸压得狠得多）。胸底 5.230 与髋线 5.085 之间只剩 0.145 m，
    #     参考的腰就是这么短的 —— 它不是一个「段」，是胸与骨盆之间的一道暗缝。
    #     上一版把腰当成 0.945 H 的一整段，于是正面从胸到裙是一整块板（=冰箱）。
    root.children.append(xform('waist', build_waist(), dy=P['waist_dy'],
                               sy=P['waist_sy'], sxz=P['tor_sxz'], pivot=pv))
    # 背鳍：跟胸同一套映射（不然胸压短之后鳍从头顶穿出来）
    root.children.append(xform(
        'bay', build_bay_clean() if CLEAN else build_bay(),
        dy=P['dy_bay'], sy=P['tor_sy'], sxz=P['tor_sxz'], pivot=pv))
    if not CLEAN:
        root.children.append(xform('funnels', build_funnels(), dy=P['dy_bay']))
    root.children.append(xform('hip', build_hip(), dy=P['hip_dy']))
    root.children.append(xform('skirt', build_skirt(), dy=P['skirt_dy']))
    wings = Node('wings')
    for s, sx in (('L', 1), ('R', -1)):
        # ★ 肩甲：宽度/高度/纵深三项已与参考实测齐平（见 SH_K 的第七版注释），
        #   这一轮不再缩放，只把它**往下长**（SH_PROF 底沿 6.52 → 5.98），
        #   让甲片罩住上臂根部 —— 用户「肩太短」指的是这件事，不是尺寸不够。
        root.children.append(xform(
            'sh_' + s,
            squeeze3('', build_shoulder(s),
                     (sx * SH_ANCHOR[0], SH_ANCHOR[1], SH_ANCHOR[2]),
                     SH_K if SH_SQUEEZE else (1.0, 1.0, 1.0)),
            dy=P['dy_arm']))
        if not CLEAN:
            wings.children.append(xform('wing_' + s, build_wing(s), dy=P['dy_bay']))
        root.children.append(xform('arm_' + s, build_arm(s), dy=P['dy_arm'],
                                   sy=P['arm_sy'], pivot=6.54,
                                   sxz=P['arm_sxz'], px=sx * 1.67))
        root.children.append(xform('leg_' + s, build_leg(s), sy=P['leg_sy'],
                                   sxz=P['leg_sxz'], ox=sx * P['leg_px']))
    root.children.append(wings)
    mesh = Mesh()
    collect2(root, mesh)
    return root, mesh


def meta_for(mesh):
    P_ = np.array(mesh.P, np.float32).reshape(-1, 3)
    y0, y1 = float(P_[:, 1].min()), float(P_[:, 1].max())
    x0, x1 = float(P_[:, 0].min()), float(P_[:, 0].max())
    z0, z1 = float(P_[:, 2].min()), float(P_[:, 2].max())
    return dict(H=y1 - y0, Wfig=x1 - x0, scale=1.0,
                zf=z1, zback=z0, cy=0.5 * (y0 + y1),
                bbox=(x0, x1, y0, y1, z0, z1))


def view_meta(meta, size):
    """渲染取景：可见高度只有 1.24·H。横向比竖向宽时必须按横向开框，
    否则肩甲整块被裁掉（第一版就栽在这）。"""
    Hm, Wm = meta['H'], meta['Wfig']
    Dm = abs(meta['zf']) + abs(meta['zback'])
    Wrot = max(Wm, Dm,
               Wm * math.cos(math.radians(35)) + Dm * math.sin(math.radians(35)))
    Wp, Hp = size
    m = dict(meta)
    m['H'] = max(Hm * 1.08, Wrot * 1.00 * Hp / (1.24 * Wp))
    return m


def count_parts(root):
    n = 0
    for c in root.children:
        if c.prim is not None:
            n += 1
        n += count_parts(c)
    return n


def stats(root, mesh, meta):
    bc = meta['bbox']
    return dict(H=round(bc[3] - bc[2], 3), W=round(bc[1] - bc[0], 3),
                D=round(bc[5] - bc[4], 3),
                WH=round((bc[1] - bc[0]) / DIM['H'], 4),
                DW=round((bc[5] - bc[4]) / (bc[1] - bc[0]), 4),
                parts=count_parts(root), tris=len(mesh))


def write_obj(mesh, path):
    P_ = np.array(mesh.P, np.float32).reshape(-1, 3)
    lines = ['# s2_graybox hardsurface  H=8.0 m  MTOW 34.9 t', 'o s2_upper']
    for p in P_:
        lines.append('v %.4f %.4f %.4f' % (p[0], p[1], p[2]))
    for i in range(0, len(P_), 3):
        lines.append('f %d %d %d' % (i + 1, i + 2, i + 3))
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return len(P_) // 3


def main():
    global WING_DEPLOY, CLEAN
    if '--deploy' in sys.argv:
        WING_DEPLOY = 1.0
    elif '--stow' in sys.argv:
        WING_DEPLOY = 0.0
    if '--clean' in sys.argv:
        CLEAN = True
    if '--no-shk' in sys.argv:
        globals()['SH_SQUEEZE'] = False
    root, mesh = build()
    meta = meta_for(mesh)
    st = stats(root, mesh, meta)
    print('=' * 78)
    print('S2 灰模 · 硬表面语法 · H=8.0 m'
          + ('（**主干构型 --clean**：无动力舱/浮游炮/折叠翼，造型研究体）'
             if CLEAN else '（核动力构型）'))
    print('=' * 78)
    # ★ 两个量必须分开报：**本体**（不含翼盒）才是和线稿 W/H 0.561 对口径的那个。
    #   折叠翼在几何上等于「把展向长度换成弦向宽度」，叶根必然外凸 —— 这是
    #   折叠的代价，不是没折好。拿含翼包络去比 0.561 只会得到一个假结论。
    mb = Mesh()
    for c in root.children:
        if c.name != 'wings':
            collect2(c, mb)
    stb = stats(root, mb, meta_for(mb))
    tag = '收纳态' if WING_DEPLOY < 0.5 else '展开态'
    print(f'  翼盒状态    {tag}')
    print(f'  本体包络    {stb["W"]:.3f} × {stb["H"]:.3f} × {stb["D"]:.3f} m')
    print(f'  本体 W/H    {stb["WH"]:.4f}   目标 0.561')
    print(f'  本体 D/W    {stb["DW"]:.4f}   目标 0.627')
    print(f'  全机包络    {st["W"]:.3f} × {st["H"]:.3f} × {st["D"]:.3f} m'
          f'   （含翼，W/H {st["WH"]:.4f}）')
    print(f'  零件数      {st["parts"]}')
    print(f'  三角形      {st["tris"]}')

    # 另一构型的包络：同一套零件、只改翼盒展开角。
    # ★ 两个构型必须各报各的，不能拿展开态的翼展去算 W/H
    #   —— 线稿的 0.561 对的是收纳态。
    # ★ --clean 没有翼盒，这条不成立，跳过。
    if not CLEAN:
        alt = 1.0 - WING_DEPLOY
        WING_DEPLOY = alt
        r2, m2 = build()
        st2 = stats(r2, m2, meta_for(m2))
        WING_DEPLOY = 1.0 - alt
        t2 = '收纳态' if alt < 0.5 else '展开态'
        print(f'  另一构型    {t2}：包络 {st2["W"]:.3f} × {st2["H"]:.3f} × '
              f'{st2["D"]:.3f} m，W/H {st2["WH"]:.4f}（翼展 {st2["W"]:.3f} m）')

    if '--check' in sys.argv:
        import volume_check as VC
        print()
        VC.measure(mesh, meta, verbose=True, label='S2 灰模（硬表面）')
        ok, msg = VC.structure_gate(*VC.manifold_stats(mesh)[1:])
        print(f'  V6 结构门：{"✓ 通过" if ok else "✗ 不合格"}  {msg}')

    if '--views' in sys.argv:
        import render_relief as RR
        from PIL import Image
        outd = os.path.join(HERE, 'out', 's2c' if CLEAN else 's2')
        os.makedirs(outd, exist_ok=True)
        size = (760, 900)
        # 翼盒另出一张展开态对照（同一机位、同一光照），
        # 因为「折起来好不好看」和「展开好不好看」是两个问题。
        states = [('', WING_DEPLOY)]
        if not CLEAN and ('--deploy' in sys.argv or '--stow' in sys.argv):
            states.append(('_alt', 1.0 - WING_DEPLOY))
        for suffix, dep in states:
            WING_DEPLOY = dep
            r_, m_ = build()
            vm = view_meta(meta_for(m_), size)
            paths, masks = [], []
            for name, yaw in (('front', 0.0), ('q35', 35.0), ('side', 90.0),
                              ('back', 180.0)):
                pre = 's2c' if CLEAN else 's2'
                p = os.path.join(outd, '%s_%s%s.png' % (pre, name, suffix))
                m, _ = RR.render(m_, vm, yaw, p, size=size, bg_lv=0.55)
                paths.append(p)
                masks.append(m)
                print(f'  → {p}')
            w, h = size
            sheet = Image.new('RGB', (w * 4, h * 2), (40, 40, 44))
            for i, p in enumerate(paths):
                sheet.paste(Image.open(p), (i * w, 0))
                m = Image.fromarray((masks[i] * 255).astype(np.uint8))
                m = m.resize((w, h), Image.NEAREST)
                sil = 255 - np.array(m)
                sheet.paste(Image.fromarray(np.repeat(sil[..., None], 3, 2)),
                            (i * w, h))
            sp = os.path.join(outd, ('s2c' if CLEAN else 's2') + '_sheet%s.png' % suffix)
            sheet.save(sp)
            print(f'  → {sp}')

    if '--obj' in sys.argv:
        p = sys.argv[sys.argv.index('--obj') + 1]
        os.makedirs(os.path.dirname(p) or '.', exist_ok=True)
        n = write_obj(mesh, p)
        print(f'  → {p}  ({n} 三角)')

    if '--json' in sys.argv:
        p = sys.argv[sys.argv.index('--json') + 1]
        os.makedirs(os.path.dirname(p) or '.', exist_ok=True)
        with open(p, 'w') as f:
            json.dump(dict(stats=st, dim=DIM, bbox=meta['bbox']), f,
                      ensure_ascii=False, indent=2, default=float)
        print(f'  → {p}')


if __name__ == '__main__':
    main()
