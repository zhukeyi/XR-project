def _clip_z(poly, zlo, zhi):
    """把 (z, y) 闭合多边形裁到 z ∈ [zlo, zhi]（Sutherland–Hodgman，两次半平面裁剪）。

    ★ 为什么要裁而不用手写每个分段的坐标：脚的分段边界（趾箱后沿、脚背转折、
      足弓前后）在**顶边和底边上的 y 不一样**，手算 8 个交点很容易把某一边
      算错 0.01，结果就是两片甲叶之间露出一道楔形缝或者互相插进去。
      程序裁出来的一定是原轮廓的严格子集，缝宽就是传进去的 0.016，可控。
    """
    def clip(poly, keep_z_ge):
        out = []
        n = len(poly)
        for k in range(n):
            a, b = poly[k], poly[(k + 1) % n]
            ain = (a[0] >= zlo) if keep_z_ge else (a[0] <= zhi)
            bin_ = (b[0] >= zlo) if keep_z_ge else (b[0] <= zhi)
            if ain:
                out.append(a)
            if ain != bin_:
                if abs(b[0] - a[0]) < 1e-9:
                    continue
                t = ((zlo - a[0]) if keep_z_ge else (zhi - a[0])) / (b[0] - a[0])
                out.append((a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])))
        return out

    p = clip(list(poly), True)
    if len(p) < 3:
        return []
    p = clip(p, False)
    return p if len(p) >= 3 else []


