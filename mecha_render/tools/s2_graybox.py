def _wing_panel(s, ang, sweep, zc, mat, r1=1.85, pts=None, th=None):
    """单片散热叶。局部 +X 展向、Y 弦向、Z 板厚（板面法线朝 Z）。

    ★★ `Node.rot` 的单位是**度，不是弧度**（r3d.Rx/Ry/Rz 内部自己转弧度）。
      第一版这里套了 math.radians，−87 被当成 −87 度 ≈ 0 度，
      三片叶全躺在水平位不动，包围盒一点没变 —— 换了三版才发现单位错。
      直接传度即可。
    """
    if pts is None:
        pts = [(WING_R0, -WING_W0), (WING_R0, WING_W0),
               (r1, WING_W1), (r1, -WING_W1)]
    a, b = float(ang), float(sweep)
    if s < 0:
        pts = [(-x, y) for (x, y) in pts]
        a, b = -a, -b
    return Node('', g_plate(pts, WING_TH if th is None else th, 'z'), mat,
                pos=(s * WING_HX, WING_HY, zc), rot=(0.0, b, a))


def build_wing(side):
    n = Node('wing_%s' % side)
    s = +1 if side == 'L' else -1

    # 1 铰座：把翼盒挂在吊臂收拢段的**外侧**，是受力件不是装饰
    n.children.append(L([
        (6.82, R(s * 1.74, s * 1.90, -1.92, -1.26, 0.04)),
        (7.04, R(s * 1.74, s * 1.90, -1.90, -1.28, 0.04)),
    ], FRAME))

    # 2 铰轴：★ P3 要求分缝落在铰链上。没有这道深色轴，三片叶就是
    #   「贴了三块板」；有了它，背视能读出「这里能转」。
    n.children.append(L([
        (6.90, R(s * 1.79, s * 1.87, -1.93, -1.25, 0.02)),
        (6.98, R(s * 1.79, s * 1.87, -1.93, -1.25, 0.02)),
    ], INK))

    # 3/4/5 三片散热叶：扇形张开。明度交替（ARMOR / ARMOR2），
    #   因为三片在背视里会互相叠压，同色会糊成一整块。
    if WING_DEPLOY > 0.5:
        specs = [(WING_ANG_DEPLOY[i], WING_SWEEP_DEPLOY) for i in range(3)]
    else:
        specs = [(WING_ANG_STOW[i], 0.0) for i in range(3)]
    for i, (ang, swp) in enumerate(specs):
        n.children.append(_wing_panel(
            s, ang, swp, WING_ZC[i],
            ARMOR if i % 2 == 0 else ARMOR2, r1=WING_R1S[i]))

    # 6 叶根整流：盖住三片叶的根部，避免「三块板插在背上」
    n.children.append(L([
        (6.84, R(s * 1.75, s * 1.95, -1.94, -1.24, 0.05)),
        (7.02, R(s * 1.79, s * 1.91, -1.90, -1.28, 0.04)),
        (7.12, R(s * 1.77, s * 1.87, -1.84, -1.34, 0.03)),
    ], ARMOR2))

    # 7 翼尖游标：给 RCS 一个长力臂（§16.6 的 α 是按 3.0 m 力臂算的）。
    #   ★ 与最外那片共用同一组 rot/pos，所以收纳态它自动跑到下方，
    #     不需要第二套坐标 —— 这是「构型跟着铰点走」的正确写法。
    rt = WING_R1S[-1]
    # ★ 叶尖半弦已加到 0.18，游标必须比叶片更宽才露得出来（0.070 → 0.105），
    #   否则整块嵌进叶里等于没加。
    tip = [(rt - 0.24, -0.105), (rt - 0.24, 0.105),
           (rt + 0.02, 0.072), (rt + 0.02, -0.072)]
    n.children.append(_wing_panel(
        s, specs[-1][0], specs[-1][1], WING_ZC[-1], INK,
        r1=rt, pts=tip, th=WING_TH + 0.045))
    return n


