"""tools/s2_graybox.py — S2 局部灰模（硬表面语法版）：头 + 胸 + 双肩 + 上臂 + 腰髋

为什么整体重写
  第一版所有主形体都用 `r3d.g_loft`（超椭圆，14 边均布，相邻面夹角 25.7°）。
  它的设计意图就是「方中带圆」，做出来的东西**必然是圆滚滚的** —— 那不是参数
  没调好，是基元选错了。硬表面装甲的语法是反的：一个大平面 + 一两道斜切，
  平面相交出锐棱，外缘可以收成刀口。所以改用 tools/hardsurface.py 的
  多边形放样 / 多边形挤出，形状控制权交回给调用方。

三条外形原则（本文件所有零件都受它约束）
  P1 折面：截面只准 4–8 边凸多边形，斜切量 ≥0.06×最小边。禁止连续小转角。
  P2 刀口：肩甲 / 披膊 / 髋根的外缘厚度收到 0.35 倍，内缘保持厚。
  P3 第一性原理：**每条装甲分缝必须落在内部结构边界上** ——
     胸甲竖缝落在中脊侧壁，肩缝落在吊臂铰座，腰缝落在腰回转轴承，
     面罩缝落在座舱盖框。刻线不是花纹，是内部结构在外表面的投影。

参考的三条风格线
  科技（特斯拉式减法）：能用一块大平面就不拆成三块；机体零曲面，
      曲面只留给必须气动的地方（机翼、风扇整流罩）。
  铁血：外露铰链、液压筒、警示红段；接缝留影线，不做贴合。
  中国风：腰封（明光铠）、护心镜（六边形）、披膊三层叠压（山文甲）、暗金描边。

基准（nuclear_mecha.py §7/§8）：H=8.0 m，MTOW 34.9 t，
动力舱 4.93 m³ 装 5.74 t 布雷顿机组，电机分到四具吊臂。

坐标：米。Y 上（脚底 0、头顶 8.0），+Z 朝正面，X 向右为 +。

用法
  python3 tools/s2_graybox.py --check        # V6 / V3 两道门
  python3 tools/s2_graybox.py --views        # 四视图
  python3 tools/s2_graybox.py --obj out/s2/s2_graybox.obj
"""
